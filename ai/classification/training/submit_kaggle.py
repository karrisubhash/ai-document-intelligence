"""Assemble, push and collect a Kaggle GPU training run.

Kaggle takes a single source file per kernel, so the shared modules are
vendored in ahead of the training body at submit time rather than
duplicated in a notebook that would immediately drift.

    python -m ai.classification.training.submit_kaggle --smoke
    python -m ai.classification.training.submit_kaggle \
        --dataset chan814/rvl-cdip --epochs 5

Needs Kaggle credentials: KAGGLE_USERNAME + KAGGLE_KEY, or
~/.kaggle/kaggle.json from https://www.kaggle.com/settings -> API.
"""

import argparse
import json
import time
from pathlib import Path

from ai.common.kaggle import (
    download_output,
    load_credentials,
    push_kernel,
    wait_for_kernel,
)

REPO_ROOT = Path(__file__).resolve().parents[3]
VENDORED = [
    REPO_ROOT / "ai" / "classification" / "evaluation" / "metrics.py",
    REPO_ROOT / "ai" / "classification" / "training" / "train_vision.py",
]
LABELS_MODULE = REPO_ROOT / "ai" / "classification" / "datasets" / "base.py"


def extract_labels() -> str:
    """Lift the LABELS tuple out of datasets/base.py so the kernel has
    exactly the same label order as everything else."""
    source = LABELS_MODULE.read_text(encoding="utf-8")
    start = source.index("LABELS = (")
    end = source.index(")", start) + 1
    return source[start:end]


def build_kernel_source(argv: list) -> str:
    """Concatenate shared modules and the training body into one script."""
    parts = [
        '"""Generated by ai/classification/training/submit_kaggle.py.',
        "Do not edit in the Kaggle UI - regenerate and push instead.",
        '"""',
        "import sys",
        "",
        f"# --- vendored from {LABELS_MODULE.relative_to(REPO_ROOT)} ---",
        extract_labels(),
        "",
    ]

    for path in VENDORED:
        body = path.read_text(encoding="utf-8")
        # Drop the guarded package imports; the names are already defined
        # above by the time the training body runs.
        body = body.replace(
            "try:\n"
            "    from ai.classification.datasets.base import LABELS\n"
            "    from ai.classification.evaluation.metrics import evaluate, render, render_confusion\n"
            "except ImportError:  # pragma: no cover - vendored path\n"
            "    pass\n",
            "",
        )
        # Only the final module may run its main().
        body = body.replace('if __name__ == "__main__":\n    main()\n', "")
        parts += [f"# --- vendored from {path.relative_to(REPO_ROOT)} ---", body, ""]

    arguments = json.dumps(argv)
    parts += [
        "# --- entrypoint ---",
        f"sys.argv = ['train_vision.py'] + {arguments}",
        "main()",
        "",
    ]

    return "\n".join(parts)


def training_argv(args) -> list:
    argv = [
        "--arch",
        args.arch,
        "--epochs",
        str(args.epochs),
        "--batch-size",
        str(args.batch_size),
        "--image-size",
        str(args.image_size),
        "--workers",
        str(args.workers),
        "--model-version",
        args.model_version,
    ]
    if args.per_class is not None:
        argv += ["--per-class", str(args.per_class)]
    if args.smoke:
        argv.append("--smoke")
    if args.require_gpu:
        argv.append("--require-gpu")
    return argv


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dataset",
        action="append",
        dest="datasets",
        default=None,
        help="Kaggle dataset to mount at /kaggle/input (repeatable). "
        "Defaults to a canonical-path image mirror plus the "
        "official split files.",
    )
    parser.add_argument(
        "--require-gpu", action="store_true", help="Fail rather than fall back to CPU."
    )
    parser.add_argument("--slug", default="rvlcdip-vision-baseline")
    parser.add_argument("--title", default="RVL-CDIP vision baseline")
    parser.add_argument("--arch", default="resnet50")
    parser.add_argument("--model-version", default="0.1.0")
    parser.add_argument("--epochs", type=int, default=5)
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--image-size", type=int, default=224)
    parser.add_argument("--workers", type=int, default=2)
    parser.add_argument("--per-class", type=int, default=None)
    parser.add_argument(
        "--smoke",
        action="store_true",
        help="1 epoch, 20 images/class - proves the path cheaply.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=REPO_ROOT / "ai" / "classification" / "artifacts",
    )
    parser.add_argument(
        "--no-wait", action="store_true", help="Push and exit without polling."
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Assemble and print the kernel without pushing.",
    )
    parser.add_argument("--poll-seconds", type=int, default=60)
    args = parser.parse_args()

    source = build_kernel_source(training_argv(args))

    if args.dry_run:
        print(source)
        print(
            f"\n--- {len(source.splitlines())} lines, "
            f"{len(source.encode()) / 1024:.1f} KB ---"
        )
        return

    credentials = load_credentials()
    # Canonical imagesX/... paths preserved, so the official split files
    # apply; the kernel fetches those itself over its internet access.
    datasets = args.datasets or ["ducktard/rvlcdip"]
    metadata = {
        "id": f"{credentials.username}/{args.slug}",
        "title": args.title,
        "code_file": "main.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": datasets,
    }

    print(f"pushing {metadata['id']} (gpu=True)")
    for dataset in datasets:
        print(f"  dataset: {dataset}")
    response = push_kernel(metadata, source, credentials)
    print(f"  {response.get('url') or response}")

    if args.no_wait:
        print("not waiting; poll with the Kaggle UI or re-run without --no-wait.")
        return

    started = time.time()

    def on_poll(state, _status):
        print(f"  [{time.time() - started:7.0f}s] {state}")

    status = wait_for_kernel(
        credentials.username,
        args.slug,
        credentials,
        poll_seconds=args.poll_seconds,
        on_poll=on_poll,
    )
    print(f"final state: {status.get('status')} {status.get('failureMessage') or ''}")

    if (status.get("status") or "").strip() != "complete":
        raise SystemExit("kernel did not complete; not downloading output.")

    destination = (
        args.output_dir / "document-classifier-vision" / f"v{args.model_version}"
    )
    written = download_output(credentials.username, args.slug, credentials, destination)
    print(f"downloaded {len(written)} file(s) -> {destination}")
    for name in written:
        print(f"  {name}")


if __name__ == "__main__":
    main()
